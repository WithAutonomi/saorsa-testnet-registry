"""Per-uploader wallet creation, funding, and draining on Arbitrum Sepolia.

Each testnet uploader VM runs with its own EOA wallet. Wallets are generated by
``create_wallet``, funded from the main testnet funding wallet via
``fund_wallet``, and on destroy any remaining ANT/ETH is swept back to the
funding wallet via ``drain_wallet``.

The funding source is the existing ``--wallet-secret-key`` (also accepted via
``ANT_DEPLOY_SECRET_KEY``) — it must be an EOA on Arbitrum Sepolia.

Production uploads use a different code path entirely; this module is testnet
only.
"""

from __future__ import annotations

from dataclasses import dataclass
from decimal import Decimal
from typing import Any

from eth_account import Account
from web3 import Web3

# Standard ERC-20 ABI subset — balanceOf, transfer, decimals.
ERC20_ABI: list[dict[str, Any]] = [
    {
        "name": "balanceOf",
        "type": "function",
        "stateMutability": "view",
        "inputs": [{"name": "account", "type": "address"}],
        "outputs": [{"name": "", "type": "uint256"}],
    },
    {
        "name": "transfer",
        "type": "function",
        "stateMutability": "nonpayable",
        "inputs": [
            {"name": "to", "type": "address"},
            {"name": "amount", "type": "uint256"},
        ],
        "outputs": [{"name": "", "type": "bool"}],
    },
    {
        "name": "decimals",
        "type": "function",
        "stateMutability": "view",
        "inputs": [],
        "outputs": [{"name": "", "type": "uint8"}],
    },
]

# Reserve a small amount of ETH in each per-uploader wallet so that the drain
# transaction itself has gas available. Anything below this is left behind.
ETH_GAS_RESERVE_WEI = Web3.to_wei("0.0005", "ether")


@dataclass(frozen=True)
class Wallet:
    address: str
    secret_key: str  # 0x-prefixed 32-byte hex


def _normalize_secret_key(key: str) -> str:
    key = key.strip()
    if not key.startswith("0x"):
        key = "0x" + key
    return key


def create_wallet() -> Wallet:
    """Generate a fresh EOA. The secret key is held in memory only — the caller
    is responsible for persisting it (typically into S3 client state)."""
    acct = Account.create()
    secret = acct.key.hex()
    if not secret.startswith("0x"):
        secret = "0x" + secret
    return Wallet(address=acct.address, secret_key=secret)


def get_web3(rpc_url: str) -> Web3:
    return Web3(Web3.HTTPProvider(rpc_url))


def _erc20(w3: Web3, token_address: str):
    return w3.eth.contract(
        address=Web3.to_checksum_address(token_address), abi=ERC20_ABI
    )


def get_eth_balance(w3: Web3, address: str) -> int:
    return w3.eth.get_balance(Web3.to_checksum_address(address))


def get_token_balance(w3: Web3, token_address: str, address: str) -> int:
    contract = _erc20(w3, token_address)
    return contract.functions.balanceOf(Web3.to_checksum_address(address)).call()


def get_token_decimals(w3: Web3, token_address: str) -> int:
    return _erc20(w3, token_address).functions.decimals().call()


def _send_signed(w3: Web3, signed_tx) -> str:
    raw = getattr(signed_tx, "raw_transaction", None) or signed_tx.rawTransaction
    tx_hash = w3.eth.send_raw_transaction(raw)
    receipt = w3.eth.wait_for_transaction_receipt(tx_hash)
    if receipt.status != 1:
        raise RuntimeError(f"Transaction {tx_hash.hex()} reverted")
    return tx_hash.hex()


def _gas_fields(w3: Web3) -> dict:
    """Compute gas fields with headroom against base-fee fluctuations.

    Arbitrum's base fee can move between fee estimation and tx submission;
    web3.py's defaults occasionally produce a `maxFeePerGas` below the
    next-block base fee, which gets rejected with
    "max fee per gas less than block base fee". We pre-compute fields with
    a 2x base-fee buffer.
    """
    try:
        latest = w3.eth.get_block("latest")
        base_fee = latest.get("baseFeePerGas")
    except Exception:
        base_fee = None
    if base_fee is not None:
        priority_fee = Web3.to_wei("0.1", "gwei")
        max_fee = base_fee * 2 + priority_fee
        return {
            "maxFeePerGas": max_fee,
            "maxPriorityFeePerGas": priority_fee,
        }
    return {"gasPrice": int(w3.eth.gas_price * 2)}


def transfer_eth(w3: Web3, from_secret_key: str, to_address: str, value_wei: int) -> str:
    """Send `value_wei` of native ETH from `from_secret_key` to `to_address`."""
    acct = Account.from_key(_normalize_secret_key(from_secret_key))
    to_checksum = Web3.to_checksum_address(to_address)
    nonce = w3.eth.get_transaction_count(acct.address)
    tx = {
        "to": to_checksum,
        "value": value_wei,
        "nonce": nonce,
        "chainId": w3.eth.chain_id,
        "gas": 21_000,
        **_gas_fields(w3),
    }
    signed = acct.sign_transaction(tx)
    return _send_signed(w3, signed)


def transfer_token(
    w3: Web3,
    token_address: str,
    from_secret_key: str,
    to_address: str,
    amount_units: int,
) -> str:
    """Send `amount_units` (already in token decimals) of an ERC-20 from
    `from_secret_key` to `to_address`."""
    acct = Account.from_key(_normalize_secret_key(from_secret_key))
    contract = _erc20(w3, token_address)
    nonce = w3.eth.get_transaction_count(acct.address)
    fn = contract.functions.transfer(
        Web3.to_checksum_address(to_address), amount_units
    )
    tx = fn.build_transaction(
        {
            "from": acct.address,
            "nonce": nonce,
            "chainId": w3.eth.chain_id,
            **_gas_fields(w3),
        }
    )
    signed = acct.sign_transaction(tx)
    return _send_signed(w3, signed)


def to_token_units(amount: Decimal | float | str | int, decimals: int) -> int:
    """Convert a human-readable amount (e.g. Decimal("100")) into token base units."""
    return int(Decimal(str(amount)) * (Decimal(10) ** decimals))


def fund_wallet(
    w3: Web3,
    funding_secret_key: str,
    token_address: str,
    target_address: str,
    ant_amount: Decimal | float | str | int,
    eth_amount: Decimal | float | str | int,
) -> dict[str, str]:
    """Transfer ``ant_amount`` of the payment token and ``eth_amount`` ETH from
    the funding wallet to ``target_address``. Returns {tx_kind: tx_hash}.

    Sends ETH first so the new wallet has gas to interact later, then ANT.
    """
    eth_wei = Web3.to_wei(Decimal(str(eth_amount)), "ether")
    decimals = get_token_decimals(w3, token_address)
    ant_units = to_token_units(ant_amount, decimals)

    eth_tx = transfer_eth(w3, funding_secret_key, target_address, eth_wei)
    ant_tx = transfer_token(
        w3, token_address, funding_secret_key, target_address, ant_units
    )
    return {"eth_tx": eth_tx, "ant_tx": ant_tx}


def drain_wallet(
    w3: Web3,
    uploader_secret_key: str,
    token_address: str,
    funding_address: str,
    gas_reserve_wei: int = ETH_GAS_RESERVE_WEI,
) -> dict[str, str | None]:
    """Sweep all ANT and (almost) all ETH from the uploader wallet back to
    ``funding_address``.

    ANT is sent first (uses ETH for gas), then ETH minus a reserve to cover its
    own transfer. If a balance is zero, that leg is skipped and reported as
    None in the result.
    """
    acct = Account.from_key(_normalize_secret_key(uploader_secret_key))
    result: dict[str, str | None] = {"ant_tx": None, "eth_tx": None}

    ant_balance = get_token_balance(w3, token_address, acct.address)
    if ant_balance > 0:
        result["ant_tx"] = transfer_token(
            w3,
            token_address,
            uploader_secret_key,
            funding_address,
            ant_balance,
        )

    eth_balance = get_eth_balance(w3, acct.address)
    gas = _gas_fields(w3)
    # Worst-case gas price: maxFeePerGas under EIP-1559, gasPrice under legacy.
    effective_gas_price = gas.get("maxFeePerGas", gas.get("gasPrice", 0))
    eth_tx_cost = effective_gas_price * 21_000
    sweep_amount = eth_balance - eth_tx_cost - gas_reserve_wei
    if sweep_amount > 0:
        # Send manually so we can control gas without re-querying.
        nonce = w3.eth.get_transaction_count(acct.address)
        tx = {
            "to": Web3.to_checksum_address(funding_address),
            "value": sweep_amount,
            "nonce": nonce,
            "chainId": w3.eth.chain_id,
            "gas": 21_000,
            **gas,
        }
        signed = acct.sign_transaction(tx)
        result["eth_tx"] = _send_signed(w3, signed)

    return result


def address_for_secret_key(secret_key: str) -> str:
    """Return the EOA address corresponding to a secret key."""
    return Account.from_key(_normalize_secret_key(secret_key)).address
